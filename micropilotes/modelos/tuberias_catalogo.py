def propiedades(tubo):
    from dataclasses import asdict
    return {**asdict(tubo),'referencia':tubo.etiqueta,'di_mm':tubo.de_mm-2*tubo.t_mm,
            'carga_catalogo_kN':tubo.carga_catalogo_kN}

def personalizada(de,t):
    if not 0<t<de/2:
        raise ValueError('Espesor o diametro personalizado incompatible.')
    di=de-2*t
    a=pi/4*(de**2-di**2)/100
    i=pi/64*(de**4-di**4)/10000
    return Tubo(de,t,i/(de/20),i,a,a*.785,None)
